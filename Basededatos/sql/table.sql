CREATE TABLE IF NOT EXISTS alumnos (
  id INT(20) AUTO_INCREMENT PRIMARY KEY,
  nombre_alumno TEXT (30) NOT NULL,
  apellido_alumno TEXT (30) NOT NULL,
  dni_alumno VARCHAR(10) NOT NULL,
  celular_alumno VARCHAR(25) NOT NULL,
  estado_alumno BOOLEAN NOT NULL DEFAULT TRUE,
) 

CREATE TABLE IF NOT EXISTS años (
  id_año INT AUTO_INCREMENT PRIMARY KEY,
  nombre_año TEXT (30) NOT NULL, 
  estado_año BOOLEAN NOT NULL DEFAULT TRUE,
)

CREATE TABLE  IF NOT EXISTS division (
    id_DIVISION INT AUTO_INCREMENT PRIMARY KEY,
    nombre_DIVISION TEXT(30) NOT NULL,
    estado_division BOOLEAN NOT NULL DEFAULT TRUE
);